import { execFile } from 'node:child_process';
import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { promisify } from 'node:util';

const exec = promisify(execFile);
const { stdout } = await exec('npm', ['pack', '--json'], { maxBuffer: 10 * 1024 * 1024 });
const packed = JSON.parse(stdout)[0];
const archive = resolve(packed.filename);
const consumer = await mkdtemp(resolve(tmpdir(), 'gws-consumer-'));
await writeFile(resolve(consumer, 'package.json'), JSON.stringify({ private: true, type: 'module' }));
await exec('npm', ['install', '--ignore-scripts', archive], { cwd: consumer, maxBuffer: 10 * 1024 * 1024 });
await writeFile(resolve(consumer, 'run.mjs'), `
import { createLocalProvider, synthesize, toFlatGeobuf, toGeoJson, toProvJson } from 'geospatial-world-synthesis';
import { createGeoJsonHttpProvider, createLocalFileProvider, createOpenStreetMapMapProvider } from 'geospatial-world-synthesis/providers';
import { createJsonDirectoryStore, createOvertureMapsProvider, loadWorkflowConfig } from 'geospatial-world-synthesis/node';
if (typeof createGeoJsonHttpProvider !== 'function') throw new Error('Provider subpath unavailable');
if (typeof createLocalFileProvider !== 'function' || typeof createOpenStreetMapMapProvider !== 'function') throw new Error('Expanded provider subpath unavailable');
if (typeof createJsonDirectoryStore !== 'function' || typeof loadWorkflowConfig !== 'function') throw new Error('Node subpath unavailable');
if (typeof createOvertureMapsProvider !== 'function') throw new Error('Overture Node provider unavailable');
const provider = createLocalProvider({ id: 'outside', sourceCrs: 'OGC:CRS84', licenseId: 'CC0-1.0', records: [{ sourceId: '1', entityType: 'poi', geometry: { type: 'Point', coordinates: [0, 0] }, properties: { name: 'Outside consumer' } }] });
const result = await synthesize({ bounds: [-1, -1, 1, 1], providers: [provider] });
if (result.entities[0].resolved.name !== 'Outside consumer') throw new Error('Unexpected result');
if (toGeoJson(result).features.length !== 1) throw new Error('Unexpected export');
if (toFlatGeobuf(result).byteLength < 100) throw new Error('Unexpected FlatGeobuf export');
if (Object.keys(toProvJson(result).wasDerivedFrom).length !== 1) throw new Error('Unexpected PROV-JSON export');
console.log(result.fingerprint);
`);
const result = await exec(process.execPath, ['run.mjs'], { cwd: consumer });
if (!/^[a-f0-9]{64}\n?$/.test(result.stdout)) throw new Error(`Unexpected consumer output: ${result.stdout}`);
const installed = JSON.parse(await readFile(resolve(consumer, 'node_modules/geospatial-world-synthesis/package.json'), 'utf8'));
const cli = await exec('npm', ['exec', '--', 'gws', '--version'], { cwd: consumer });
if (cli.stdout.trim() !== installed.version) throw new Error(`Installed CLI returned ${cli.stdout.trim()}, expected ${installed.version}`);
console.log(`Installed ${installed.name}@${installed.version} into an external temporary project and used core, provider, Node, and export entry points.`);
